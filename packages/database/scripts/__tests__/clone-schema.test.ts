import type pg from "pg";
import { describe, expect, it, vi } from "vitest";
import {
  CLONE_BEGIN_SQL,
  CloneFailedError,
  cloneDataFromPublic,
  cloneFailureCodeOf,
  DEFAULT_CLONE_CONNECT_TIMEOUT_MS,
  DEFAULT_CLONE_LOCK_TIMEOUT_MS,
  DEFAULT_CLONE_STATEMENT_TIMEOUT_MS,
  isCloneableColumn,
} from "../clone-schema";

const PREVIEW_SCHEMA = "preview_feature_branch_abc123";
const DATABASE_URL =
  "postgresql://user:pass@db.example.com:5432/closedloop?sslmode=require";

const TABLES_CATALOG_QUERY = /c\.relkind = 'r'/;
const PER_TABLE_TIMING_LOG = /document: 3 rows \(\d+ms\)/;
const CLONE_SUMMARY_TIMING_LOG = /Cloned 1 tables .*\(\d+ms\)/;
const RESTORE_NOT_DEFERRABLE = / NOT DEFERRABLE$/;
const INSERT_STATEMENT = /^INSERT INTO/;

type ColumnRow = {
  column_name: string;
  is_enum: boolean;
  is_enum_array: boolean;
  enum_type: string;
  generated: string;
  identity: string;
};

function col(
  overrides: Partial<ColumnRow> & { column_name: string }
): ColumnRow {
  return {
    is_enum: false,
    is_enum_array: false,
    enum_type: "text",
    generated: "",
    identity: "",
    ...overrides,
  };
}

/**
 * A fake pg.Client that records every issued statement and answers the three
 * catalog shapes `cloneDataFromPublic` asks for. `tableColumns` is the target
 * schema's columns; `sourceColumnNames` defaults to every target column name so
 * a test only has to say when the two differ.
 */
function makeClient(opts: {
  tables?: string[];
  tableColumns?: Record<string, ColumnRow[]>;
  sourceColumnNames?: Record<string, string[]>;
  fkEdges?: { child: string; parent: string }[];
  targetFkConstraints?: { table_name: string; constraint_name: string }[];
  userTriggers?: { tableName: string; triggerName: string; enabled: string }[];
  requireDeferredBeforeInsert?: boolean;
  failOnConnect?: Error;
  failOnStatement?: { match: RegExp; error: Error };
}) {
  const tables = opts.tables ?? [];
  const issued: string[] = [];
  let constraintsDeferred = false;
  const client = {
    connect: vi.fn(() => {
      if (opts.failOnConnect) {
        return Promise.reject(opts.failOnConnect);
      }
      return Promise.resolve();
    }),
    end: vi.fn(() => Promise.resolve()),
    query: vi.fn((sql: string, params?: unknown[]) => {
      issued.push(sql);
      if (sql === CLONE_BEGIN_SQL || sql === "COMMIT" || sql === "ROLLBACK") {
        constraintsDeferred = false;
        return Promise.resolve({ rowCount: null, rows: [] });
      }
      if (sql.startsWith("SET CONSTRAINTS ALL ")) {
        constraintsDeferred = sql === "SET CONSTRAINTS ALL DEFERRED";
        return Promise.resolve({ rowCount: null, rows: [] });
      }
      if (
        sql.startsWith("INSERT INTO") &&
        opts.requireDeferredBeforeInsert &&
        !constraintsDeferred
      ) {
        return Promise.reject(new Error("FK constraints were not deferred"));
      }
      if (opts.failOnStatement?.match.test(sql)) {
        return Promise.reject(opts.failOnStatement.error);
      }
      if (sql.includes("pg_catalog.pg_attribute a")) {
        const schema = String(params?.[0]);
        const table = String(params?.[1]);
        const all = opts.tableColumns?.[table] ?? [];
        if (schema === "public") {
          const names =
            opts.sourceColumnNames?.[table] ?? all.map((c) => c.column_name);
          return Promise.resolve({
            rows: all.filter((c) => names.includes(c.column_name)),
          });
        }
        return Promise.resolve({ rows: all });
      }
      if (
        sql.includes("c.relkind = 'r'") &&
        !sql.includes("pg_catalog.pg_trigger")
      ) {
        return Promise.resolve({
          rows: tables.map((table_name) => ({ table_name })),
        });
      }
      if (sql.includes("con.conname AS constraint_name")) {
        return Promise.resolve({ rows: opts.targetFkConstraints ?? [] });
      }
      if (sql.includes("con.contype = 'f'")) {
        return Promise.resolve({ rows: opts.fkEdges ?? [] });
      }
      if (sql.includes("pg_catalog.pg_trigger")) {
        return Promise.resolve({ rows: opts.userTriggers ?? [] });
      }
      // INSERT ... SELECT
      return Promise.resolve({ rowCount: 3 });
    }),
  };
  return { client: client as unknown as pg.Client, issued, spies: client };
}

function makeLogger() {
  return { log: vi.fn(), warn: vi.fn(), error: vi.fn() };
}

describe("isCloneableColumn", () => {
  it("excludes GENERATED ALWAYS and identity columns, keeps ordinary ones", () => {
    expect(isCloneableColumn({ generated: "", identity: "" })).toBe(true);
    // search_documents.tsv (FEA-3857) — the column that broke every clone.
    expect(isCloneableColumn({ generated: "s", identity: "" })).toBe(false);
    // GENERATED ALWAYS AS IDENTITY — Postgres rejects an explicit value.
    expect(isCloneableColumn({ generated: "", identity: "a" })).toBe(false);
    // GENERATED BY DEFAULT AS IDENTITY — Postgres ACCEPTS an explicit value, so
    // it must still be cloned; dropping it would re-number rows and orphan
    // every FK pointing at the original id.
    expect(isCloneableColumn({ generated: "", identity: "d" })).toBe(true);
  });
});

describe("cloneDataFromPublic — statement bounds (ISS-5285)", () => {
  it("sets lock_timeout and statement_timeout BEFORE the first catalog query", async () => {
    const { client, issued } = makeClient({ tables: [] });

    await cloneDataFromPublic(DATABASE_URL, PREVIEW_SCHEMA, {
      createClient: () => client,
      logger: makeLogger(),
      env: {},
    });

    const lockIndex = issued.findIndex((sql) => sql.includes("lock_timeout"));
    const statementIndex = issued.findIndex((sql) =>
      sql.includes("statement_timeout")
    );
    const firstCatalogIndex = issued.findIndex((sql) =>
      sql.includes("c.relkind = 'r'")
    );

    expect(lockIndex).toBeGreaterThanOrEqual(0);
    expect(statementIndex).toBeGreaterThanOrEqual(0);
    expect(firstCatalogIndex).toBeGreaterThan(lockIndex);
    expect(firstCatalogIndex).toBeGreaterThan(statementIndex);
    expect(issued[lockIndex]).toContain(`${DEFAULT_CLONE_LOCK_TIMEOUT_MS}ms`);
    expect(issued[statementIndex]).toContain(
      `${DEFAULT_CLONE_STATEMENT_TIMEOUT_MS}ms`
    );
  });

  it("honors env overrides and falls back to defaults on an invalid value", async () => {
    const overridden = makeClient({ tables: [] });
    await cloneDataFromPublic(DATABASE_URL, PREVIEW_SCHEMA, {
      createClient: () => overridden.client,
      logger: makeLogger(),
      env: {
        CLONE_LOCK_TIMEOUT_MS: "1234",
        CLONE_STATEMENT_TIMEOUT_MS: "5678",
      },
    });
    expect(overridden.issued.some((s) => s.includes("1234ms"))).toBe(true);
    expect(overridden.issued.some((s) => s.includes("5678ms"))).toBe(true);

    const invalid = makeClient({ tables: [] });
    await cloneDataFromPublic(DATABASE_URL, PREVIEW_SCHEMA, {
      createClient: () => invalid.client,
      logger: makeLogger(),
      env: {
        CLONE_LOCK_TIMEOUT_MS: "not-a-number",
        CLONE_STATEMENT_TIMEOUT_MS: "-5",
      },
    });
    expect(
      invalid.issued.some((s) =>
        s.includes(`${DEFAULT_CLONE_LOCK_TIMEOUT_MS}ms`)
      )
    ).toBe(true);
    expect(
      invalid.issued.some((s) =>
        s.includes(`${DEFAULT_CLONE_STATEMENT_TIMEOUT_MS}ms`)
      )
    ).toBe(true);
  });

  it("fails with a CloneFailedError on a statement timeout and still ends the client", async () => {
    const { client, spies } = makeClient({
      tables: ["document"],
      failOnStatement: {
        match: TABLES_CATALOG_QUERY,
        error: new Error("canceling statement due to statement timeout"),
      },
    });
    const logger = makeLogger();

    await expect(
      cloneDataFromPublic(DATABASE_URL, PREVIEW_SCHEMA, {
        createClient: () => client,
        logger,
        env: {},
      })
    ).rejects.toThrow(CloneFailedError);
    expect(spies.end).toHaveBeenCalledTimes(1);
    expect(logger.error).toHaveBeenCalledWith(
      expect.stringContaining("statement timeout")
    );
  });

  it("bounds the connect itself (pg defaults connectionTimeoutMillis to wait-forever)", async () => {
    const { client } = makeClient({ tables: [] });
    let seen: { connectionTimeoutMillis?: number } | undefined;

    await cloneDataFromPublic(DATABASE_URL, PREVIEW_SCHEMA, {
      createClient: (_url, opts) => {
        seen = opts;
        return client;
      },
      logger: makeLogger(),
      env: {},
    });

    expect(seen?.connectionTimeoutMillis).toBe(
      DEFAULT_CLONE_CONNECT_TIMEOUT_MS
    );
  });

  it("fails with a CloneFailedError on a CONNECT failure and still ends the client (regression: connect was outside the try)", async () => {
    const { client, spies } = makeClient({
      failOnConnect: new Error(
        'PAM authentication failed for user "vercel_iam"'
      ),
    });
    const logger = makeLogger();

    await expect(
      cloneDataFromPublic(DATABASE_URL, PREVIEW_SCHEMA, {
        createClient: () => client,
        logger,
        env: {},
      })
    ).rejects.toThrow(CloneFailedError);
    expect(spies.end).toHaveBeenCalledTimes(1);
    expect(logger.error).toHaveBeenCalledWith(
      expect.stringContaining("PAM authentication failed")
    );
  });

  it("logs elapsed time per table and in the summary", async () => {
    let clock = 0;
    const { client } = makeClient({
      tables: ["document"],
      tableColumns: { document: [col({ column_name: "id" })] },
    });
    const logger = makeLogger();

    await cloneDataFromPublic(DATABASE_URL, PREVIEW_SCHEMA, {
      createClient: () => client,
      logger,
      env: {},
      now: () => {
        clock += 10;
        return clock;
      },
    });

    expect(logger.log).toHaveBeenCalledWith(
      expect.stringMatching(PER_TABLE_TIMING_LOG)
    );
    expect(logger.log).toHaveBeenCalledWith(
      expect.stringMatching(CLONE_SUMMARY_TIMING_LOG)
    );
  });
});

describe("cloneDataFromPublic — FK cycles (ISS-5344)", () => {
  it("defers target FK checks before inserting cyclic tables", async () => {
    const alphaAlter = `ALTER TABLE "${PREVIEW_SCHEMA}"."alpha" ALTER CONSTRAINT "alpha_beta_fkey" DEFERRABLE INITIALLY IMMEDIATE`;
    const betaAlter = `ALTER TABLE "${PREVIEW_SCHEMA}"."beta" ALTER CONSTRAINT "beta_alpha_fkey" DEFERRABLE INITIALLY IMMEDIATE`;
    const alphaRestore = `ALTER TABLE "${PREVIEW_SCHEMA}"."alpha" ALTER CONSTRAINT "alpha_beta_fkey" NOT DEFERRABLE`;
    const betaRestore = `ALTER TABLE "${PREVIEW_SCHEMA}"."beta" ALTER CONSTRAINT "beta_alpha_fkey" NOT DEFERRABLE`;
    const { client, issued } = makeClient({
      tables: ["alpha", "beta"],
      fkEdges: [
        { child: "alpha", parent: "beta" },
        { child: "beta", parent: "alpha" },
      ],
      targetFkConstraints: [
        { table_name: "alpha", constraint_name: "alpha_beta_fkey" },
        { table_name: "beta", constraint_name: "beta_alpha_fkey" },
      ],
      tableColumns: {
        alpha: [col({ column_name: "id" }), col({ column_name: "beta_id" })],
        beta: [col({ column_name: "id" }), col({ column_name: "alpha_id" })],
      },
      requireDeferredBeforeInsert: true,
    });

    await cloneDataFromPublic(DATABASE_URL, PREVIEW_SCHEMA, {
      createClient: () => client,
      logger: makeLogger(),
      env: {},
    });

    const beginIndex = issued.indexOf(CLONE_BEGIN_SQL);
    const alphaAlterIndex = issued.indexOf(alphaAlter);
    const betaAlterIndex = issued.indexOf(betaAlter);
    const setDeferredIndex = issued.indexOf("SET CONSTRAINTS ALL DEFERRED");
    const setImmediateIndex = issued.indexOf("SET CONSTRAINTS ALL IMMEDIATE");
    const alphaRestoreIndex = issued.indexOf(alphaRestore);
    const betaRestoreIndex = issued.indexOf(betaRestore);
    const firstInsertIndex = issued.findIndex((sql) =>
      sql.startsWith("INSERT INTO")
    );
    const lastInsertIndex = issued.reduce(
      (latest, sql, index) => (sql.startsWith("INSERT INTO") ? index : latest),
      -1
    );

    expect(beginIndex).toBeGreaterThanOrEqual(0);
    expect(alphaAlterIndex).toBeGreaterThan(beginIndex);
    expect(betaAlterIndex).toBeGreaterThan(alphaAlterIndex);
    expect(setDeferredIndex).toBeGreaterThan(betaAlterIndex);
    expect(firstInsertIndex).toBeGreaterThan(setDeferredIndex);
    expect(setImmediateIndex).toBeGreaterThan(lastInsertIndex);
    expect(alphaRestoreIndex).toBeGreaterThan(setImmediateIndex);
    expect(betaRestoreIndex).toBeGreaterThan(alphaRestoreIndex);
    expect(issued.indexOf("COMMIT")).toBeGreaterThan(betaRestoreIndex);
    expect(issued).not.toContain("ROLLBACK");
  });
});

describe("cloneDataFromPublic — bounded FK validation (ISS-6424)", () => {
  it("drains each deferred FK in its own statement, not one whole-schema check", async () => {
    const { client, issued } = makeClient({
      tables: ["organization", "document", "document_version"],
      fkEdges: [
        { child: "document", parent: "organization" },
        { child: "document_version", parent: "document" },
        { child: "document_version", parent: "organization" },
      ],
      // document_version carries TWO FKs: real Postgres rejects `ALTER TABLE`
      // on a relation that still has pending trigger events, so a drain
      // interleaved with the restores would fail on the second one.
      targetFkConstraints: [
        {
          table_name: "document",
          constraint_name: "document_organization_id_fkey",
        },
        {
          table_name: "document_version",
          constraint_name: "document_version_document_id_fkey",
        },
        {
          table_name: "document_version",
          constraint_name: "document_version_organization_id_fkey",
        },
      ],
      tableColumns: {
        organization: [col({ column_name: "id" })],
        document: [col({ column_name: "id" }), col({ column_name: "org_id" })],
        document_version: [
          col({ column_name: "id" }),
          col({ column_name: "document_id" }),
          col({ column_name: "org_id" }),
        ],
      },
    });

    await cloneDataFromPublic(DATABASE_URL, PREVIEW_SCHEMA, {
      createClient: () => client,
      logger: makeLogger(),
      env: {},
    });

    // Positive control: all three tables were really copied, so the drain below
    // ran against a populated constraint set rather than an empty one.
    expect(issued.filter((sql) => sql.startsWith("INSERT INTO"))).toHaveLength(
      3
    );
    expect(perConstraintDrains(issued)).toEqual([
      `SET CONSTRAINTS "${PREVIEW_SCHEMA}"."document_organization_id_fkey" IMMEDIATE`,
      `SET CONSTRAINTS "${PREVIEW_SCHEMA}"."document_version_document_id_fkey" IMMEDIATE`,
      `SET CONSTRAINTS "${PREVIEW_SCHEMA}"."document_version_organization_id_fkey" IMMEDIATE`,
    ]);

    const drainIndexes = issued
      .map((sql, index) => (isPerConstraintDrain(sql) ? index : -1))
      .filter((index) => index >= 0);
    const lastInsertIndex = issued.reduce(
      (latest, sql, index) => (sql.startsWith("INSERT INTO") ? index : latest),
      -1
    );
    const firstRestoreIndex = issued.findIndex((sql) =>
      RESTORE_NOT_DEFERRABLE.test(sql)
    );
    // Hoisting the blanket sweep above the drains would fire the whole schema's
    // pending events from one statement again — the drains behind it are then
    // no-ops, and every other assertion here still holds. Pin it last.
    const sweepIndex = issued.indexOf("SET CONSTRAINTS ALL IMMEDIATE");

    expect(Math.min(...drainIndexes)).toBeGreaterThan(lastInsertIndex);
    expect(Math.max(...drainIndexes)).toBeLessThan(sweepIndex);
    expect(sweepIndex).toBeLessThan(firstRestoreIndex);
    expect(issued).not.toContain("ROLLBACK");
  });

  it("keeps every FK deferred through the copy, cyclic or not (ISS-5344 not narrowed)", async () => {
    const { client, issued } = makeClient({
      // alpha <-> beta is a cycle; gamma -> alpha is ordinary and acyclic.
      tables: ["alpha", "beta", "gamma"],
      fkEdges: [
        { child: "alpha", parent: "beta" },
        { child: "beta", parent: "alpha" },
        { child: "gamma", parent: "alpha" },
      ],
      targetFkConstraints: [
        { table_name: "alpha", constraint_name: "alpha_beta_fkey" },
        { table_name: "beta", constraint_name: "beta_alpha_fkey" },
        { table_name: "gamma", constraint_name: "gamma_alpha_fkey" },
      ],
      tableColumns: {
        alpha: [col({ column_name: "id" }), col({ column_name: "beta_id" })],
        beta: [col({ column_name: "id" }), col({ column_name: "alpha_id" })],
        gamma: [col({ column_name: "id" }), col({ column_name: "alpha_id" })],
      },
      requireDeferredBeforeInsert: true,
    });

    await cloneDataFromPublic(DATABASE_URL, PREVIEW_SCHEMA, {
      createClient: () => client,
      logger: makeLogger(),
      env: {},
    });

    expect(issued.filter((sql) => sql.startsWith("INSERT INTO"))).toHaveLength(
      3
    );
    expect(perConstraintDrains(issued)).toEqual([
      `SET CONSTRAINTS "${PREVIEW_SCHEMA}"."alpha_beta_fkey" IMMEDIATE`,
      `SET CONSTRAINTS "${PREVIEW_SCHEMA}"."beta_alpha_fkey" IMMEDIATE`,
      `SET CONSTRAINTS "${PREVIEW_SCHEMA}"."gamma_alpha_fkey" IMMEDIATE`,
    ]);
    // `SET CONSTRAINTS ALL DEFERRED` only reaches a constraint that was granted
    // DEFERRABLE first, so gamma — the acyclic table — has to be granted it too.
    // Without this, narrowing the grant loop to the cycle would leave gamma's FK
    // validating inside its own INSERT, sharing one budget with the row copy.
    const gammaGrantIndex = issued.indexOf(
      `ALTER TABLE "${PREVIEW_SCHEMA}"."gamma" ALTER CONSTRAINT "gamma_alpha_fkey" DEFERRABLE INITIALLY IMMEDIATE`
    );
    const firstInsertIndex = issued.findIndex((sql) =>
      sql.startsWith("INSERT INTO")
    );

    expect(gammaGrantIndex).toBeGreaterThanOrEqual(0);
    expect(gammaGrantIndex).toBeLessThan(firstInsertIndex);
  });
});

