import { createHash } from "node:crypto";
import type pg from "pg";
import {
  COLUMNS_SQL,
  type ColInfo,
  getTablesInFkOrder,
  isCloneableColumn,
  withDeferredTargetConstraints,
} from "./clone-schema";
import { quoteIdentifier } from "./db-utils";
import { isPreviewSchema } from "./preview-schema";

/**
 * ISS-12056: loading a seeded vibe environment into its preview schema.
 *
 * The vibe seed runs on a GitHub runner against a throwaway local database
 * (its guard accepts nothing else), and the runner cannot reach the stage
 * database. So the seeded rows travel as JSON through the preview API, in
 * batches small enough for a request, into a staging table INSIDE the preview
 * schema. One transaction then moves them into the real tables with the same
 * deferred-constraint, triggers-off load the `public` clone uses, so batch
 * order never has to follow the foreign keys.
 *
 * Nothing here can reach another schema: every statement names the target
 * schema explicitly, the schema must be a preview schema, and every table and
 * column is checked against that schema's own catalog before it is used.
 */

export const VIBE_SEED_STAGING_TABLE = "_vibe_seed_rows";

/**
 * Infrastructure tables that are never seeded, and the staging table itself.
 * The runner's export skips the same set, so both ends agree.
 */
export const NEVER_RESTORED_TABLES: ReadonlySet<string> = new Set([
  "_prisma_migrations",
  "preview_schemas",
  "preview_schemas_observations",
  VIBE_SEED_STAGING_TABLE,
]);

export class VibeSeedRestoreError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "VibeSeedRestoreError";
  }
}

type QueryClient = Pick<pg.Client, "query">;

/**
 * Stages one batch of rows for `table`. The key is stable for an exact retry
 * after a lost response, while `rowsJson` reaches Postgres without any value
 * round-tripping through a JavaScript number.
 */
export async function stageVibeSeedRows(
  client: QueryClient,
  schema: string,
  table: string,
  rowsJson: string
): Promise<{ staged: number }> {
  assertPreviewSchema(schema);
  await assertRestorableTable(client, schema, table);
  const staging = `${quoteIdentifier(schema)}.${quoteIdentifier(VIBE_SEED_STAGING_TABLE)}`;
  const batchKey = createHash("sha256")
    .update(table)
    .update(Buffer.from([0]))
    .update(rowsJson)
    .digest("hex");
  await client.query(
    `CREATE TABLE IF NOT EXISTS ${staging} (
       id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
       batch_key text NOT NULL UNIQUE,
       table_name text NOT NULL,
       rows jsonb NOT NULL
     )`
  );
  const { rows } = await client.query<{
    staged: number | null;
    valid: boolean;
  }>(
    `WITH batch AS (SELECT $3::jsonb AS value),
     valid_batch AS (
       SELECT value FROM batch
       WHERE jsonb_typeof(value) = 'array'
         AND NOT EXISTS (
           SELECT 1 FROM jsonb_array_elements(value) AS element
           WHERE jsonb_typeof(element) <> 'object'
         )
     ),
     written AS (
       INSERT INTO ${staging} AS staged_batch (batch_key, table_name, rows)
       SELECT $1, $2, value FROM valid_batch
       ON CONFLICT (batch_key) DO UPDATE SET rows = EXCLUDED.rows
       WHERE staged_batch.table_name = EXCLUDED.table_name
         AND staged_batch.rows = EXCLUDED.rows
       RETURNING jsonb_array_length(rows) AS staged
     )
     SELECT (SELECT staged FROM written) AS staged,
            EXISTS(SELECT 1 FROM valid_batch) AS valid`,
    [batchKey, table, rowsJson]
  );
  const result = rows[0];
  if (!result?.valid) {
    throw new VibeSeedRestoreError(
      `rows for ${table} must be a JSON array of objects`
    );
  }
  if (result.staged === null) {
    throw new VibeSeedRestoreError(
      `the staged batch key for ${table} conflicts with different rows`
    );
  }
  return { staged: result.staged };
}

export type VibeSeedRestoreSummary = {
  tables: number;
  rows: number;
};

/**
 * Moves every staged row into its table in one transaction, resets the
 * schema's sequences past the loaded ids, drops the staging table, and runs
 * `inTransaction` (the caller's organization binding) inside the same
 * transaction. Throws, leaving the schema as it was, when a staged table or
 * column does not exist here.
 */
export async function restoreStagedVibeSeedRows(
  client: pg.Client,
  schema: string,
  logger: Pick<Console, "log" | "warn">,
  inTransaction: (client: pg.Client) => Promise<void>
): Promise<VibeSeedRestoreSummary> {
  assertPreviewSchema(schema);
  const staging = `${quoteIdentifier(schema)}.${quoteIdentifier(VIBE_SEED_STAGING_TABLE)}`;
  await client.query("BEGIN");
  try {
    const stagedTables = await readStagedTables(client, schema);
    const ordered = (await getTablesInFkOrder(client, logger, schema)).filter(
      (table) => !NEVER_RESTORED_TABLES.has(table)
    );
    const unknown = [...stagedTables].filter(
      (table) => !ordered.includes(table)
    );
    if (unknown.length > 0) {
      throw new VibeSeedRestoreError(
        `staged rows name tables this schema does not have: ${unknown.sort().join(", ")}`
      );
    }
    let restoredRows = 0;
    await withDeferredTargetConstraints(client, schema, async () => {
      for (const table of ordered.filter((name) => stagedTables.has(name))) {
        restoredRows += await restoreTable(client, schema, table);
      }
    });
    await resetSequences(client, schema);
    await client.query(`DROP TABLE ${staging}`);
    await inTransaction(client);
    await client.query("COMMIT");
    logger.log(
      `✓ Restored ${restoredRows} seeded row(s) across ${stagedTables.size} table(s) into ${schema}`
    );
    return { tables: stagedTables.size, rows: restoredRows };
  } catch (error) {
    await client.query("ROLLBACK").catch(() => {
      // Keep the restore's own failure, which is the one the caller reports.
    });
    throw error;
  }
}

async function readStagedTables(
  client: QueryClient,
  schema: string
): Promise<Set<string>> {
  const { rows: exists } = await client.query<{ present: boolean }>(
    "SELECT to_regclass($1) IS NOT NULL AS present",
    [`${quoteIdentifier(schema)}.${quoteIdentifier(VIBE_SEED_STAGING_TABLE)}`]
  );
  if (!exists[0]?.present) {
    throw new VibeSeedRestoreError(`no seeded rows were staged in ${schema}`);
  }
  const { rows } = await client.query<{ table_name: string }>(
    `SELECT DISTINCT table_name FROM ${quoteIdentifier(schema)}.${quoteIdentifier(VIBE_SEED_STAGING_TABLE)}`
  );
  return new Set(rows.map((row) => row.table_name));
}

async function restoreTable(
  client: QueryClient,
  schema: string,
  table: string
): Promise<number> {
  const staging = `${quoteIdentifier(schema)}.${quoteIdentifier(VIBE_SEED_STAGING_TABLE)}`;
  const target = `${quoteIdentifier(schema)}.${quoteIdentifier(table)}`;
  const { rows: targetCols } = await client.query<ColInfo>(COLUMNS_SQL, [
    schema,
    table,
  ]);
  const { rows: keyRows } = await client.query<{ key: string }>(
    `SELECT DISTINCT jsonb_object_keys(element) AS key
     FROM ${staging} AS batch
     CROSS JOIN LATERAL jsonb_array_elements(batch.rows) AS element
     WHERE batch.table_name = $1`,
    [table]
  );
  const stagedKeys = new Set(keyRows.map((row) => row.key));
  const targetNames = new Set(targetCols.map((col) => col.column_name));
  const missing = [...stagedKeys].filter((key) => !targetNames.has(key));
  if (missing.length > 0) {
    throw new VibeSeedRestoreError(
      `${table} has no column(s) ${missing.sort().join(", ")} in ${schema}; the seed ran against a newer schema than this preview`
    );
  }
  const cols = targetCols
    .filter((col) => stagedKeys.has(col.column_name) && isCloneableColumn(col))
    .map((col) => quoteIdentifier(col.column_name));
  if (cols.length === 0) {
    return 0;
  }
  const columnList = cols.join(", ");
  const { rowCount } = await client.query(
    `INSERT INTO ${target} (${columnList})
     SELECT ${cols.map((col) => `record.${col}`).join(", ")}
     FROM ${staging} AS batch
     CROSS JOIN LATERAL jsonb_populate_recordset(NULL::${target}, batch.rows) AS record
     WHERE batch.table_name = $1
     ORDER BY batch.id`,
    [table]
  );
  return rowCount ?? 0;
}

/**
 * Explicit ids were inserted, so every sequence a column owns is moved past
 * the largest value now in that column; otherwise the first insert the app
 * makes collides with a seeded row.
 */
async function resetSequences(
  client: QueryClient,
  schema: string
): Promise<void> {
  const { rows } = await client.query<{
    sequence_name: string;
    table_name: string;
    column_name: string;
  }>(
    `SELECT seq.relname AS sequence_name, tbl.relname AS table_name, col.attname AS column_name
     FROM pg_catalog.pg_depend dep
     JOIN pg_catalog.pg_class seq ON seq.oid = dep.objid AND seq.relkind = 'S'
     JOIN pg_catalog.pg_class tbl ON tbl.oid = dep.refobjid
     JOIN pg_catalog.pg_attribute col ON col.attrelid = tbl.oid AND col.attnum = dep.refobjsubid
     WHERE seq.relnamespace = to_regnamespace($1)
       AND dep.deptype IN ('a', 'i')`,
    [schema]
  );
  const quotedSchema = quoteIdentifier(schema);
  for (const row of rows) {
    if (row.table_name === VIBE_SEED_STAGING_TABLE) {
      continue;
    }
    const sequence = `${quotedSchema}.${quoteIdentifier(row.sequence_name)}`;
    await client.query(
      `SELECT setval($1::regclass, COALESCE((SELECT max(${quoteIdentifier(row.column_name)}) FROM ${quotedSchema}.${quoteIdentifier(row.table_name)}), 0) + 1, false)`,
      [sequence]
    );
  }
}

async function assertRestorableTable(
  client: QueryClient,
  schema: string,
  table: string
): Promise<void> {
  if (NEVER_RESTORED_TABLES.has(table)) {
    throw new VibeSeedRestoreError(`${table} is never seeded`);
  }
  const { rows } = await client.query(
    `SELECT 1 FROM pg_catalog.pg_class
     WHERE relnamespace = to_regnamespace($1) AND relname = $2 AND relkind = 'r'`,
    [schema, table]
  );
  if (rows.length === 0) {
    throw new VibeSeedRestoreError(`${schema} has no table ${table}`);
  }
}

function assertPreviewSchema(schema: string): void {
  if (!isPreviewSchema(schema)) {
    throw new VibeSeedRestoreError(
      `refusing to load seeded rows into ${schema}: only branch preview schemas are vibe environments`
    );
  }
}
