-- ISS-7259: mark the per-session component usage row that is the session's
-- FIRST ATTRIBUTED SKILL, as the harness stamped it.
--
-- A FLAG on the existing usage row rather than a row of its own: "invoked in
-- this session" and "first attributed in this session" are facts about the same
-- (session, kind, key, branch) tuple, so a second row would count one skill
-- twice and inflate every rollup that sums this table.
--
-- NULLABLE, and only TRUE or NULL is ever written. The wire OMITS the field for
-- a row that is not the attributed skill, so at this boundary an absent value
-- covers both "an older desktop never sent it" and "a current desktop sent the
-- payload and this row is not the one" — the two are genuinely indistinguishable
-- here, and NULL is the only honest way to say so. Writing FALSE would assert we
-- looked and found this row was not attributed, which is exactly the claim an
-- older desktop's payload cannot support. Every consumer filters on
-- `is_first_attributed_skill = true`, for which NULL and FALSE behave alike, so
-- nothing is lost by refusing to invent the distinction.
--
-- Generated by `prisma migrate diff --from-schema/--to-schema` (file-based, no
-- database contacted) rather than `migrate dev`, because the local Postgres is
-- shared by every git worktree and applying is a separate, permissioned step.
ALTER TABLE "agent_component_session_usage" ADD COLUMN     "is_first_attributed_skill" BOOLEAN;
