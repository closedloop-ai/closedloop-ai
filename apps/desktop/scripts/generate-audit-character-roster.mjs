// @ts-check
/**
 * FEA-4013 — discover the full Audit Bot review-character cast from the shipped
 * prompt files and emit the committed roster module
 * `src/shared/audit-character-roster.generated.ts`.
 *
 * The desktop audit picker used to expose only a hardcoded 4-member list, while
 * the app ships ~41 character prompt files under
 * `resources/audit-characters/**\/*.md` (the full cast, grouped by author
 * folder). This script is the single discovery point: it walks that tree,
 * derives each character's id / label / short description / filing tag / group
 * from the file, and writes them as a typed `AUDIT_CHARACTER_ROSTER` the
 * renderer picker and the main-process IPC validator both consume — so a new
 * character file surfaces in the picker after a regenerate, with no hand-edited
 * enum to drift.
 *
 * The character `id` is the prompt file's path relative to
 * `resources/audit-characters/`, minus the `.md` extension (e.g.
 * `kaitic/desktop-denny`). That id is exactly what the crewd runner resolves as
 * `join(promptsDir, `${id}.md`)`, so every roster entry maps 1:1 to a prompt
 * the runner can actually launch.
 *
 * `shared/*` is EXCLUDED — those are shared infra prompt fragments
 * (`code-review`, `cross-reference`, `pr-responder`, `review-reply`), not
 * runnable review characters.
 *
 * Regenerated by `pnpm prebuild` ahead of build / typecheck / test. Committed
 * (not gitignored) so the picker and the guard run without a prebuild step and
 * the roster diff is reviewable. Idempotent + content-aware so repeated runs do
 * not churn.
 *
 * Drift protection is TWO-part, because the parity test alone cannot catch a
 * stale committed roster on the normal path — prebuild regenerates the file
 * before any test imports it (FEA-4013 review):
 *   1. `--check` mode (this script) re-renders and exits non-zero WITHOUT
 *      writing when the on-disk file differs, so a CI step run BEFORE prebuild
 *      fails a stale commit. The `verify:audit-roster` package script wraps it.
 *   2. `audit-character-roster.test.ts` asserts the in-memory roster still
 *      matches the shipped prompt tree (catches a hand-edited or deleted file).
 *
 * ISS-5303 moved the pure parsing half — every string-in/string-out derivation
 * this script performs — into `generate-audit-character-roster-lib.mjs`, so it
 * can be unit-tested without importing this side-effecting entrypoint. What
 * stays here is the part that touches the world: the filesystem walk, the TS
 * rendering, and the three-way up-to-date / write / `--check` decision below.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  groupForId,
  groupLabelFor,
  parseLabelAndDescription,
  tagForId,
} from "./generate-audit-character-roster-lib.mjs";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const appDir = path.join(scriptDir, "..");
const charactersDir = path.join(appDir, "resources", "audit-characters");
const outFile = path.join(
  appDir,
  "src",
  "shared",
  "audit-character-roster.generated.ts"
);

/** Author subfolders excluded from the cast (shared infra prompt fragments). */
const EXCLUDED_DIRS = new Set(["shared"]);

/** The `.md` prompt-file extension, stripped to form the character id. */
const MD_EXT_RE = /\.md$/;

/** Recursively collect character prompt ids (path relative to the dir, no `.md`). */
function collectCharacterIds(rel = "") {
  /** @type {string[]} */
  const ids = [];
  const dir = path.join(charactersDir, rel);
  const entries = existsSync(dir)
    ? readdirSync(dir, { withFileTypes: true })
    : [];
  for (const entry of entries) {
    const childRel = rel ? `${rel}/${entry.name}` : entry.name;
    if (entry.isDirectory()) {
      if (!EXCLUDED_DIRS.has(entry.name)) {
        ids.push(...collectCharacterIds(childRel));
      }
    } else if (entry.isFile() && entry.name.endsWith(".md")) {
      ids.push(childRel.replace(MD_EXT_RE, ""));
    }
  }
  return ids;
}

/**
 * Build the sorted roster entries from the discovered character files.
 *
 * Labels are disambiguated: when two characters derive the same display name
 * (e.g. a core `docs-darwin` and a nightly `kaitic/docs-darwin`), the
 * non-`core` entries are qualified with their friendly author name — "Docs
 * Darwin (Kai Tic)", not the raw folder slug — so the picker never renders two
 * indistinguishable options and the qualifier reads as a person, not a bug
 * (FEA-4013 review). The cleaned description differentiates them further.
 */
function buildRoster() {
  const base = collectCharacterIds()
    .sort((a, b) => a.localeCompare(b))
    .map((id) => {
      const raw = readFileSync(path.join(charactersDir, `${id}.md`), "utf8");
      const { label, description } = parseLabelAndDescription(raw, id);
      const group = groupForId(id);
      return {
        id,
        label,
        description,
        tag: tagForId(id),
        group,
        groupLabel: groupLabelFor(group),
      };
    });
  const labelCounts = new Map();
  for (const entry of base) {
    labelCounts.set(entry.label, (labelCounts.get(entry.label) ?? 0) + 1);
  }
  return base.map((entry) => {
    if (labelCounts.get(entry.label) > 1 && entry.group !== "core") {
      return { ...entry, label: `${entry.label} (${entry.groupLabel})` };
    }
    return entry;
  });
}

/** Serialize a string as a valid double-quoted TS literal. */
function toStringLiteral(value) {
  return JSON.stringify(value);
}

/** Render one roster entry as a TS object literal line. */
function renderEntry(entry) {
  return [
    "  {",
    `    id: ${toStringLiteral(entry.id)},`,
    `    label: ${toStringLiteral(entry.label)},`,
    `    description: ${toStringLiteral(entry.description)},`,
    `    tag: ${toStringLiteral(entry.tag)},`,
    `    group: ${toStringLiteral(entry.group)},`,
    `    groupLabel: ${toStringLiteral(entry.groupLabel)},`,
    "  },",
  ].join("\n");
}

function renderModule(roster) {
  const entries = roster.map(renderEntry).join("\n");
  return `// GENERATED by scripts/generate-audit-character-roster.mjs — DO NOT EDIT.
// Regenerated by \`pnpm prebuild\`; drift-guarded by \`pnpm verify:audit-roster\`.
// Source of truth: apps/desktop/resources/audit-characters/**/*.md (FEA-4013).

/**
 * One review character in the Audit Bot cast. \`id\` is the prompt file's path
 * relative to \`resources/audit-characters/\` (no \`.md\`) — exactly what the crewd
 * runner resolves — so every entry maps to a prompt the runner can launch.
 */
export type AuditCharacterRosterEntry = {
  /** Prompt-file id relative to the characters dir (e.g. "kaitic/desktop-denny"). */
  id: string;
  /** Display name shown in the picker. */
  label: string;
  /** One-line description of what the character reviews. */
  description: string;
  /** The ClosedLoop tag stamped on every issue this character files. */
  tag: string;
  /** Picker group key: the author folder, or "core" for a top-level character. */
  group: string;
  /** Human heading for {@link AuditCharacterRosterEntry.group} (e.g. "Kai Tic"). */
  groupLabel: string;
};

/**
 * The full cast of Audit Bot review characters, discovered from the shipped
 * prompt files. Sorted by id; grouped for display by {@link AuditCharacterRosterEntry.group}.
 */
export const AUDIT_CHARACTER_ROSTER: readonly AuditCharacterRosterEntry[] = [
${entries}
];
`;
}

const roster = buildRoster();
const next = renderModule(roster);
const current = existsSync(outFile) ? readFileSync(outFile, "utf8") : "";
const checkOnly = process.argv.includes("--check");

if (current === next) {
  process.stdout.write(
    `generate-audit-character-roster: up to date (${roster.length} characters)\n`
  );
} else if (checkOnly) {
  // Drift guard for CI: the committed roster is stale vs. the prompt files. We
  // do NOT rewrite it here (that would mask the drift the same way running the
  // generator before the parity test does); we fail so the operator regenerates
  // and commits. This is the mode CI runs before `prebuild` regenerates.
  process.stderr.write(
    "generate-audit-character-roster: committed roster is stale — " +
      "run `pnpm -C apps/desktop exec node scripts/generate-audit-character-roster.mjs` and commit the result.\n"
  );
  process.exit(1);
} else {
  writeFileSync(outFile, next);
  process.stdout.write(
    `generate-audit-character-roster: wrote ${roster.length} characters\n`
  );
}
