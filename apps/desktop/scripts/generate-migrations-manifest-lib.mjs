// @ts-check
/**
 * FEA-1791 / PLN-886 Phase 2 — the embedded migrations manifest generator.
 *
 * Reads migration.sql files from prisma/migrations in migration order and
 * writes src/main/database/migration/migrations-manifest.ts: an ordered array
 * of { name, checksum, sql }. New migrations use 000N_<name>; the one
 * timestamp-prefixed FEA-2030 migration is kept immutable and ordered at its
 * original slot. The runtime migration runner consumes this instead of reading
 * the filesystem, so migrations survive tarball staging into the packaged asar
 * (mirrors the build-info.ts prebuild + gitignore precedent).
 *
 * Regenerated by `pnpm prebuild` ahead of build / typecheck / test. The output
 * is gitignored. Checksums are sha256 of the raw migration.sql bytes; the
 * runner compares them against the recorded checksum to detect drift.
 *
 * ISS-5303 moved the body here out of scripts/generate-migrations-manifest.mjs,
 * which is now a shell that resolves the real desktop paths off
 * `import.meta.url` and calls `generateMigrationsManifest`. Every decision the
 * generator makes lives in this module — the legacy-manifest heal, the
 * empty-directory refusal, the symlink and path-escape rejections, the
 * checksum, the render and the write-if-changed branch — so
 * test/migrations-manifest-lib.test.ts can drive them against temp fixtures
 * instead of the real checkout. Behaviour and the emitted bytes are unchanged.
 */
import { createHash } from "node:crypto";
import {
  existsSync,
  lstatSync,
  readdirSync,
  readFileSync,
  realpathSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";
import { compareMigrationDirNames } from "./migration-order.mjs";

const MIGRATION_SQL_FILENAME = "migration.sql";

/**
 * Default sink for the generator's progress/diagnostic lines. Injectable so a
 * test can read what the generator reported instead of scraping stdout.
 *
 * @param {string} line
 */
function writeStdout(line) {
  process.stdout.write(line);
}

/**
 * The pre-ISS-5185 location of the generated manifest.
 *
 * Deliberately NOT the current output path: this is the file the heal below
 * deletes, so pointing it at the live manifest would delete the artifact the
 * build just produced.
 *
 * @param {string} appDir
 * @returns {string}
 */
export function legacyManifestPath(appDir) {
  return path.join(appDir, "src", "main", "database", "migrations-manifest.ts");
}

/**
 * ISS-5185 moved the generated manifest from database/ into database/migration/.
 * The old output is gitignored, so an existing checkout that already ran
 * `pnpm prebuild` still has the stale database/migrations-manifest.ts on disk —
 * it is inside tsconfig's `src` program glob and its `./migration-runner.js`
 * import no longer resolves, so typecheck fails after updating. Delete it here
 * so prebuild heals the checkout. Best-effort: a missing file is the normal
 * case on a fresh checkout and must not fail the build. Keep this until the
 * transition window closes.
 *
 * @param {string} appDir
 * @param {(line: string) => void} [writeLine]
 * @returns {void}
 */
export function healLegacyManifest(appDir, writeLine = writeStdout) {
  const legacyOutFile = legacyManifestPath(appDir);
  try {
    rmSync(legacyOutFile, { force: true });
  } catch (error) {
    writeLine(
      `generate-migrations-manifest: could not remove legacy ${path.relative(appDir, legacyOutFile)} (${error instanceof Error ? error.message : String(error)})\n`
    );
  }
}

/**
 * The migration directory names under `migrationsDir`, in migration order.
 *
 * An empty result is a broken checkout or a mis-resolved path, never a valid
 * state — emitting an empty manifest would ship an app that silently skips
 * every migration — so it throws rather than writing one.
 *
 * @param {string} migrationsDir
 * @returns {string[]}
 */
export function readMigrationDirNames(migrationsDir) {
  const migrationDirs = readdirSync(migrationsDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort(compareMigrationDirNames);

  if (migrationDirs.length === 0) {
    throw new Error(
      `generate-migrations-manifest: no migrations found in ${migrationsDir}`
    );
  }

  return migrationDirs;
}

/**
 * Read and checksum each migration's SQL, rejecting anything that is not a
 * regular file checked into the migrations directory.
 *
 * @param {readonly string[]} migrationDirNames
 * @param {{ appDir: string, migrationsDir: string }} paths
 * @returns {{ name: string, checksum: string, sql: string }[]}
 */
export function buildMigrationEntries(migrationDirNames, paths) {
  const { appDir, migrationsDir } = paths;
  const migrationsRoot = realpathSync(migrationsDir);

  return migrationDirNames.map((name) => {
    const sqlPath = path.join(migrationsDir, name, MIGRATION_SQL_FILENAME);
    // Reject symlinked migration files and any file whose realpath escapes the
    // migrations directory — the embedded SQL runs at app boot, so it must come
    // only from a regular file checked into prisma/migrations.
    const stat = lstatSync(sqlPath);
    if (!stat.isFile() || stat.isSymbolicLink()) {
      throw new Error(
        `generate-migrations-manifest: ${path.relative(appDir, sqlPath)} must be a regular, non-symlink file`
      );
    }
    const realSqlPath = realpathSync(sqlPath);
    const relativeToRoot = path.relative(migrationsRoot, realSqlPath);
    if (relativeToRoot.startsWith("..") || path.isAbsolute(relativeToRoot)) {
      throw new Error(
        `generate-migrations-manifest: ${path.relative(appDir, sqlPath)} resolves outside ${path.relative(appDir, migrationsDir)}`
      );
    }
    const sql = readFileSync(realSqlPath, "utf8");
    const checksum = createHash("sha256").update(sql, "utf8").digest("hex");
    return { name, checksum, sql };
  });
}

/**
 * Render the generated TypeScript module for an ordered entry list.
 *
 * @param {readonly { name: string, checksum: string, sql: string }[]} entries
 * @returns {string}
 */
export function renderManifest(entries) {
  const body = entries
    .map(
      (entry) =>
        `  {\n    name: ${JSON.stringify(entry.name)},\n    checksum: ${JSON.stringify(
          entry.checksum
        )},\n    sql: ${JSON.stringify(entry.sql)},\n  },`
    )
    .join("\n");

  return `// AUTO-GENERATED by scripts/generate-migrations-manifest.mjs — do not edit.
// FEA-1791 / PLN-886 Phase 2: ordered embedded migrations for the desktop
// SQLite runtime migration runner. Regenerated by \`pnpm prebuild\`.
import type { EmbeddedMigration } from "./migration-runner.js";

export const MIGRATIONS: readonly EmbeddedMigration[] = [
${body}
];
`;
}

/**
 * Write the manifest only when its bytes changed, so a no-op prebuild does not
 * touch the file's mtime and invalidate downstream build caches.
 *
 * @param {{
 *   appDir: string,
 *   outFile: string,
 *   contents: string,
 *   migrationCount: number,
 *   writeLine?: (line: string) => void,
 * }} options
 * @returns {boolean} Whether the file was written.
 */
export function writeManifestIfChanged(options) {
  const {
    appDir,
    outFile,
    contents,
    migrationCount,
    writeLine = writeStdout,
  } = options;

  if (existsSync(outFile) && readFileSync(outFile, "utf8") === contents) {
    writeLine(
      `generate-migrations-manifest: unchanged (${migrationCount} migration(s))\n`
    );
    return false;
  }

  writeFileSync(outFile, contents, "utf8");
  writeLine(
    `generate-migrations-manifest: wrote ${migrationCount} migration(s) to ${path.relative(appDir, outFile)}\n`
  );
  return true;
}

/**
 * Heal the legacy output, read and validate the migrations, and write the
 * manifest if it changed.
 *
 * @param {{
 *   appDir: string,
 *   migrationsDir: string,
 *   outFile: string,
 *   writeLine?: (line: string) => void,
 * }} options
 * @returns {{
 *   entries: { name: string, checksum: string, sql: string }[],
 *   contents: string,
 *   wrote: boolean,
 * }}
 */
export function generateMigrationsManifest(options) {
  const { appDir, migrationsDir, outFile, writeLine = writeStdout } = options;

  healLegacyManifest(appDir, writeLine);

  const entries = buildMigrationEntries(readMigrationDirNames(migrationsDir), {
    appDir,
    migrationsDir,
  });
  const contents = renderManifest(entries);
  const wrote = writeManifestIfChanged({
    appDir,
    outFile,
    contents,
    migrationCount: entries.length,
    writeLine,
  });

  return { entries, contents, wrote };
}
