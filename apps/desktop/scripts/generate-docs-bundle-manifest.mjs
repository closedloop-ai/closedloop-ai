// @ts-check
/**
 * FEA-3843 / PRD-555 M1 — snapshot the product docs into the desktop bundle.
 *
 * Reads every `apps/web/content/docs/**\/*.mdx` page + the Fumadocs per-folder
 * `meta.json` nav tree and emits the gitignored
 * `src/main/docs-help/docs-bundle-manifest.ts`: a `DOCS_BUNDLE` value (version
 * stamp + indexed pages with title / headings / plain-text body). The
 * main-process search index and IPC bridge consume this instead of reading the
 * filesystem at runtime, so the snapshot survives asar packaging (mirrors the
 * build-info.ts / migrations-manifest.ts prebuild + gitignore precedent).
 *
 * Zero doc *content* lives in the desktop repo — the Fumadocs docs under
 * `apps/web/content/docs` (the source that serves closedloop.ai/docs) stay the
 * single source of truth (FEA-3886 retired the parallel Mintlify `apps/docs`
 * tree); this only snapshots and indexes them. The `sourceCommit` stamp (the
 * repo HEAD) lets the app show a freshness / "view latest online" affordance.
 *
 * Regenerated by `pnpm prebuild` ahead of build / typecheck / test. Kept
 * content-aware so repeated local launches do not churn mtimes.
 *
 * ISS-5303: the parsing/indexing helpers live in
 * `generate-docs-bundle-manifest-lib.mjs` so they can be unit-tested; this file
 * keeps the orchestration, the git stamp, the base64 emit and the
 * write-if-changed block.
 */
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  buildGroupIndex,
  collectMdxFiles,
  extractHeadings,
  parseFrontmatter,
  toPageId,
  toPlainText,
  toRenderMarkdown,
} from "./generate-docs-bundle-manifest-lib.mjs";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const appDir = path.join(scriptDir, "..");
const monorepoRoot = path.join(appDir, "..", "..");
const docsDir = path.join(monorepoRoot, "apps", "web", "content", "docs");
const outFile = path.join(
  appDir,
  "src",
  "main",
  "docs-help",
  "docs-bundle-manifest.ts"
);

const DOCS_SITE_URL = "https://closedloop.ai/docs";

const { groupByPage, orderedPageIds } = buildGroupIndex(docsDir);

// Fumadocs generates the REST reference pages from the OpenAPI spec: their MDX
// body is a single `export default function Layout` React component (rendered by
// <APIPage>), not prose. Indexing that JS as searchable text would pollute the
// index and render as code in the desktop reader, so these pages are indexed by
// their (rich) frontmatter title + description only, with a pointer to the full
// interactive reference online. Detected by the marker Fumadocs stamps in.
const GENERATED_MARKER = "This file was generated by Fumadocs";

const mdxFiles = collectMdxFiles(docsDir).sort();
/** @type {Map<string, { path: string; title: string; description?: string; group?: string; headings: { level: number; text: string; slug: string }[]; body: string; renderBody: string }>} */
const pagesById = new Map();
for (const relativeMdxPath of mdxFiles) {
  const pageId = toPageId(relativeMdxPath);
  const raw = readFileSync(path.join(docsDir, relativeMdxPath), "utf8");
  const { frontmatter, body } = parseFrontmatter(raw);
  const group = groupByPage.get(pageId);
  const title = (frontmatter.title ?? pageId).trim();
  const description = frontmatter.description?.trim();
  const isGenerated = raw.includes(GENERATED_MARKER);
  const onlinePointer = description
    ? `${description}\n\n[View the full interactive reference online](${DOCS_SITE_URL}/${pageId}).`
    : `[View the full interactive reference online](${DOCS_SITE_URL}/${pageId}).`;
  pagesById.set(pageId, {
    path: pageId,
    title,
    ...(description ? { description } : {}),
    ...(group ? { group } : {}),
    headings: isGenerated ? [] : extractHeadings(body),
    body: isGenerated ? "" : toPlainText(body),
    renderBody: isGenerated ? onlinePointer : toRenderMarkdown(body),
  });
}

// Order pages by the Fumadocs meta.json nav first, then any remaining
// (un-navigated) pages alphabetically, so the bundle order is deterministic and
// nav-aligned.
const orderedPages = [];
const seen = new Set();
for (const pageId of orderedPageIds) {
  const page = pagesById.get(pageId);
  if (page && !seen.has(pageId)) {
    orderedPages.push(page);
    seen.add(pageId);
  }
}
for (const pageId of [...pagesById.keys()].sort()) {
  if (!seen.has(pageId)) {
    orderedPages.push(pagesById.get(pageId));
    seen.add(pageId);
  }
}

let sourceCommit = "";
try {
  sourceCommit = execFileSync("git", ["rev-parse", "HEAD"], {
    cwd: appDir,
    encoding: "utf8",
  }).trim();
} catch {
  sourceCommit = "";
}

// A fixed generatedAt keyed to the source commit keeps the output content-stable
// across re-runs at the same HEAD (so the file does not churn on every prebuild).
const generatedAt = new Date(0).toISOString();

const bundle = {
  sourceCommit,
  generatedAt,
  docsSiteUrl: DOCS_SITE_URL,
  pages: orderedPages,
};

// Embed the bundle as a base64-encoded JSON payload split into bounded string
// parts, decoded once at module load, instead of a single ~700KB nested object
// literal.
//
// WHY (do not "simplify" this back to an inline object literal): the whole
// snapshot is inlined into the main-process `startup` chunk, which electron-vite
// runs through vite's `[vite:esbuild-transpile]` pass. esbuild's transform
// mis-parses a code chunk once it crosses a size boundary (~2MB): it drops a
// string terminator mid-object and reports a spurious "Unterminated string
// literal" on a perfectly valid quote further down (FEA-3886). The failure is
// purely positional — it tracked the cumulative chunk offset, not any bad
// character, so it fired on whichever doc page happened to straddle the boundary
// and would resurface as docs grow. Emitting the payload as short base64 parts
// keeps every source string literal small and well clear of that boundary, so
// ANY doc content is safe regardless of length or characters. `Buffer` is a
// main-process (Node) global, so the decode is available wherever this bundle is
// consumed.
const BASE64_PART_LEN = 60_000;
const base64 = Buffer.from(JSON.stringify(bundle), "utf8").toString("base64");
/** @type {string[]} */
const base64Parts = [];
for (let offset = 0; offset < base64.length; offset += BASE64_PART_LEN) {
  base64Parts.push(base64.slice(offset, offset + BASE64_PART_LEN));
}

const contents = `// AUTO-GENERATED by scripts/generate-docs-bundle-manifest.mjs — do not edit.
// FEA-3843 / PRD-555 M1: build-time snapshot of apps/web/content/docs (**/*.mdx + meta.json)
// for the desktop in-app Docs & Help search index. Regenerated by \`pnpm prebuild\`.
//
// The snapshot is stored as a base64-encoded JSON payload (split into bounded
// string parts) rather than an inline object literal so the large embedded
// content stays clear of the esbuild-transpile size boundary that corrupts a
// giant chunk (FEA-3886). See the generator for the full rationale.
import type { DocsBundle } from "./docs-bundle-types.js";

const DOCS_BUNDLE_BASE64_PARTS: readonly string[] = ${JSON.stringify(base64Parts)};

export const DOCS_BUNDLE: DocsBundle = JSON.parse(
  Buffer.from(DOCS_BUNDLE_BASE64_PARTS.join(""), "base64").toString("utf8")
) as DocsBundle;
`;

if (existsSync(outFile) && readFileSync(outFile, "utf8") === contents) {
  process.stdout.write(
    `generate-docs-bundle-manifest: unchanged (${orderedPages.length} page(s))\n`
  );
} else {
  writeFileSync(outFile, contents, "utf8");
  process.stdout.write(
    `generate-docs-bundle-manifest: wrote ${orderedPages.length} page(s) to ${path.relative(appDir, outFile)}\n`
  );
}
