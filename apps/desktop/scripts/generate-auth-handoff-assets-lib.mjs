// @ts-check
/**
 * ISS-11243 — the pure half of `generate-auth-handoff-assets.mjs`.
 *
 * The entrypoint writes `src/shared/auth-handoff-assets.generated.ts` at module
 * scope, so it cannot be imported by the node lane. Everything it derives lives
 * here: theme-block extraction, the data-URL encoding, and the rendered module
 * source. The design-system files are read through an injected reader so tests
 * can supply fixtures.
 */

export const DESIGN_SYSTEM_THEME_PATH = "styles/globals.css";
export const LOGO_LIGHT_PATH =
  "brand/logos/Horizontal/closedloop-logo-horizontal-on-light.svg";
export const LOGO_DARK_PATH =
  "brand/logos/Horizontal/closedloop-logo-horizontal-on-dark.svg";
export const FONT_PATH =
  "node_modules/geist/dist/fonts/geist-sans/Geist-Variable.woff2";
export const MISSING_THEME_MESSAGE =
  "Auth handoff could not load the design-system themes";

const LIGHT_THEME_RE = /:root\s*\{([\s\S]*?)\n\}/;
const DARK_THEME_RE = /\.dark\s*\{([\s\S]*?)\n\}/;

/**
 * @param {string} css
 * @returns {{ light: string, dark: string }}
 */
export function extractThemeBlocks(css) {
  const light = css.match(LIGHT_THEME_RE)?.[1];
  const dark = css.match(DARK_THEME_RE)?.[1];
  if (!(light && dark)) {
    throw new Error(MISSING_THEME_MESSAGE);
  }
  return { light, dark };
}

/**
 * @param {Uint8Array} bytes
 * @param {string} mime
 */
export function toDataUrl(bytes, mime) {
  return `data:${mime};base64,${Buffer.from(bytes).toString("base64")}`;
}

/**
 * The themes are read and checked before any binary asset, so a missing theme
 * block fails without touching the logos or the font.
 *
 * @param {(designSystemPath: string) => Buffer} readDesignSystemFile
 */
export function buildAuthHandoffAssets(readDesignSystemFile) {
  const { light, dark } = extractThemeBlocks(
    readDesignSystemFile(DESIGN_SYSTEM_THEME_PATH).toString("utf8")
  );
  return {
    theme: `:root {${light}\n}\n@media (prefers-color-scheme: dark) { :root {${dark}\n} }`,
    logoLight: toDataUrl(
      readDesignSystemFile(LOGO_LIGHT_PATH),
      "image/svg+xml"
    ),
    logoDark: toDataUrl(readDesignSystemFile(LOGO_DARK_PATH), "image/svg+xml"),
    font: toDataUrl(readDesignSystemFile(FONT_PATH), "font/woff2"),
  };
}

/**
 * @param {ReturnType<typeof buildAuthHandoffAssets>} assets
 */
export function renderAuthHandoffAssetsModule(assets) {
  return `// Generated by scripts/generate-auth-handoff-assets.mjs.\nexport const AUTH_HANDOFF_ASSETS = ${JSON.stringify(assets)};\n`;
}
