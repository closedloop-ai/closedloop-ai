import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const appRoot = path.resolve(import.meta.dirname, "..");
const repoRoot = path.resolve(appRoot, "..", "..");
const sourceFile = path.join(
  repoRoot,
  "packages/design-system/styles/globals.css"
);
const outFile = path.join(
  appRoot,
  "app/style-browser-token-manifest.generated.ts"
);
const checkOnly = process.argv.includes("--check");
const declarationPattern = /(?:^|\n)\s*--([a-z0-9-]+):\s*([\s\S]*?);/g;

const source = readFileSync(sourceFile, "utf8");
const tokenDefinitions = [
  ...readTokenDefinitions(source, ":root", "root"),
  ...readTokenDefinitions(source, "@theme inline", "theme"),
];
const content = buildGeneratedModule(tokenDefinitions);
const current = existsSync(outFile) ? readFileSync(outFile, "utf8") : null;

if (current === content) {
  console.log(
    `style lab token manifest up to date (${tokenDefinitions.length} tokens)`
  );
} else if (checkOnly) {
  console.error(
    "Style Lab token manifest is stale. Run `pnpm -C apps/prototypes style-lab:generate`."
  );
  process.exit(1);
} else {
  writeFileSync(outFile, content);
  console.log(
    `style lab token manifest generated (${tokenDefinitions.length} tokens)`
  );
}

function readTokenDefinitions(cssSource, selector, scope) {
  const block = readCssBlock(cssSource, selector);
  const definitions = [];
  let match = declarationPattern.exec(block);
  while (match) {
    const [, cssName, rawValue] = match;
    definitions.push({
      id: `${scope}:${cssName}`,
      label: toLabel(cssName),
      cssName,
      initialValue: normalizeCssValue(rawValue),
      category: categorizeToken(cssName),
      scope,
    });
    match = declarationPattern.exec(block);
  }
  return definitions;
}

function readCssBlock(cssSource, selector) {
  const selectorStart = cssSource.indexOf(selector);
  if (selectorStart === -1) {
    fail(`Could not find ${selector} block in design-system globals.`);
  }
  const blockStart = cssSource.indexOf("{", selectorStart);
  if (blockStart === -1) {
    fail(`Could not find the start of the ${selector} block.`);
  }

  let depth = 0;
  for (let index = blockStart; index < cssSource.length; index += 1) {
    const character = cssSource[index];
    if (character === "{") {
      depth += 1;
    } else if (character === "}") {
      depth -= 1;
      if (depth === 0) {
        return cssSource.slice(blockStart + 1, index);
      }
    }
  }

  fail(`Could not find the end of the ${selector} block.`);
}

function normalizeCssValue(value) {
  return value.trim().replace(/\s+/g, " ");
}

function categorizeToken(name) {
  if (name.startsWith("icon-")) {
    return "icon";
  }
  if (name.startsWith("text-") || name.startsWith("font-")) {
    return "type";
  }
  if (name.includes("radius") || name.includes("shadow")) {
    return "shape";
  }
  if (
    name.startsWith("spacing-") ||
    name.startsWith("tap-") ||
    name.startsWith("density-") ||
    name.startsWith("z-") ||
    name.startsWith("breakpoint-") ||
    name.includes("height") ||
    name.startsWith("animate-")
  ) {
    return "layout";
  }
  return "color";
}

function toLabel(name) {
  return name
    .split("-")
    .map((part) => {
      if (part === "ai") {
        return "AI";
      }
      return `${part.charAt(0).toUpperCase()}${part.slice(1)}`;
    })
    .join(" ");
}

function buildGeneratedModule(definitions) {
  const tokenLines = definitions.map((definition, index) => {
    const prefix = index === 0 ? "[" : "";
    const suffix = index === definitions.length - 1 ? "]" : ",";
    return `  ${quoteString(
      `${prefix}${JSON.stringify(definition)}${suffix}`
    )},`;
  });
  return `// Generated by scripts/generate-style-lab-tokens.mjs. Do not edit by hand.
// Regenerate with: pnpm -C apps/prototypes style-lab:generate
import type { TokenDefinition } from "./style-browser-editor-data";

const tokenDefinitionsJson = [
${tokenLines.join("\n")}
].join("");

export const tokenDefinitions = JSON.parse(
  tokenDefinitionsJson
) as readonly TokenDefinition[];
`;
}

function quoteString(value) {
  return `'${value.replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;
}

function fail(message) {
  console.error(message);
  process.exit(1);
}
