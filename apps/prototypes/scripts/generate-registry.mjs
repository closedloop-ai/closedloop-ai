// Generates lib/registry.generated.ts from app/p/*/prototype.meta.ts.
// Runs before dev/build/typecheck (see package.json scripts); the output is
// committed so editors and lint see a resolvable module without running it.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const appRoot = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const prototypesDir = path.join(appRoot, "app", "p");
const outFile = path.join(appRoot, "lib", "registry.generated.ts");

const slugs = existsSync(prototypesDir)
  ? readdirSync(prototypesDir, { withFileTypes: true })
      .filter((entry) => entry.isDirectory())
      .map((entry) => entry.name)
      .filter((slug) =>
        existsSync(path.join(prototypesDir, slug, "prototype.meta.ts"))
      )
      .sort()
  : [];

// Kebab-case starting with a letter, so toCamelCase always yields a valid
// JS identifier (a digit-leading slug like "2025-dashboard" would not).
const slugPattern = /^[a-z][a-z0-9]*(-[a-z0-9]+)*$/;
const invalidSlugs = slugs.filter((slug) => !slugPattern.test(slug));
if (invalidSlugs.length > 0) {
  console.error(
    `Invalid prototype slug(s): ${invalidSlugs.join(", ")}. Slugs must be kebab-case and start with a letter (e.g. "agents", "agent-detail").`
  );
  process.exit(1);
}

const toCamelCase = (slug) =>
  slug.replace(/-([a-z0-9])/g, (_, char) => char.toUpperCase());

const importLines = slugs.map(
  (slug) =>
    `import { meta as ${toCamelCase(slug)}Meta } from "@/app/p/${slug}/prototype.meta";`
);

const entries = slugs.map((slug) => `  ${toCamelCase(slug)}Meta,`);

const content = `// Generated by scripts/generate-registry.mjs. Do not edit by hand.
// Regenerate with: pnpm --filter prototypes generate:registry
${importLines.join("\n")}
import type { PrototypeMeta } from "@/lib/registry";

export const prototypes: readonly PrototypeMeta[] = [
${entries.join("\n")}
];
`;

const current = existsSync(outFile) ? readFileSync(outFile, "utf8") : null;
if (current === content) {
  console.log(`registry up to date (${slugs.length} prototypes)`);
} else {
  writeFileSync(outFile, content);
  console.log(`registry generated (${slugs.length} prototypes)`);
}
