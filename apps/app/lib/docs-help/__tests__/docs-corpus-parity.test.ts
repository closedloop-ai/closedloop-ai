import { readFileSync } from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";
import {
  buildGroupIndex as desktopBuildGroupIndex,
  collectMdxFiles as desktopCollectMdxFiles,
  extractHeadings as desktopExtractHeadings,
  parseFrontmatter as desktopParseFrontmatter,
  slugify as desktopSlugify,
  toPlainText as desktopToPlainText,
  toRenderMarkdown as desktopToRenderMarkdown,
} from "../../../../desktop/scripts/generate-docs-bundle-manifest-lib.mjs";
import {
  buildGroupIndex,
  collectMdxFiles,
  extractHeadings,
  parseFrontmatter,
  readDocsCorpus,
  resolveDocsRoot,
  toPlainText,
  toRenderMarkdown,
} from "../docs-corpus";
import { slugifyHeading } from "../docs-slug";

/**
 * ISS-10006 — web's docs reader against desktop's, over the REAL corpus.
 *
 * Web parses `apps/web/content/docs` itself rather than importing desktop's
 * build script into `apps/app` runtime code, so there are two copies of these
 * rules. That is only safe while something executes both on the same input:
 * every divergence here is a page web would render differently from the desktop
 * app and from the docs site, and the one that fails silently is the slug — a
 * mismatched anchor leaves `HelpReader` clearing the pending heading with
 * nothing said, so the reader lands at the top of the page and is told nothing.
 *
 * Importing the `.mjs` from a TEST is the point: a test is a build-time context,
 * and it is the only place the two copies may meet.
 */
const docsRoot = resolveDocsRoot(
  path.join(import.meta.dirname, "..", "..", "..")
);

const relativePaths: string[] = desktopCollectMdxFiles(docsRoot);
const MDX_EXT_RE = /\.mdx$/;
const DOCS_SITE_URL = "https://closedloop.ai/docs";
const GENERATED_MARKER = "This file was generated by Fumadocs";

describe("web's docs parser agrees with the desktop bundle generator", () => {
  it("reads a corpus at all, so the sweep below is not over nothing", () => {
    expect(relativePaths.length).toBeGreaterThan(50);
  });

  it("walks the tree to the same file list", () => {
    // Every sweep below enumerates with DESKTOP's walk, so without this web's
    // own recursion is the one rule in the copy nothing compares. A web walk
    // that skipped a subdirectory would leave all of them green and the pages
    // silently absent from Help.
    expect([...collectMdxFiles(docsRoot)].sort()).toStrictEqual(
      [...relativePaths].sort()
    );
  });

  it("produces the same frontmatter, headings, text and markdown for every page", () => {
    for (const relative of relativePaths) {
      const raw = readFileSync(path.join(docsRoot, relative), "utf8");
      const mine = parseFrontmatter(raw);
      const theirs = desktopParseFrontmatter(raw);

      expect(mine.frontmatter, relative).toStrictEqual(theirs.frontmatter);
      expect(mine.body, relative).toBe(theirs.body);
      expect(extractHeadings(mine.body), relative).toStrictEqual(
        desktopExtractHeadings(theirs.body)
      );
      expect(toPlainText(mine.body), relative).toBe(
        desktopToPlainText(theirs.body)
      );
      expect(toRenderMarkdown(mine.body), relative).toBe(
        desktopToRenderMarkdown(theirs.body)
      );
    }
  });

  it("stamps the same anchor slug on every heading in the corpus", () => {
    let checked = 0;
    for (const relative of relativePaths) {
      const raw = readFileSync(path.join(docsRoot, relative), "utf8");
      for (const heading of desktopExtractHeadings(
        desktopParseFrontmatter(raw).body
      )) {
        expect(
          slugifyHeading(heading.text),
          `${relative} ${heading.text}`
        ).toBe(desktopSlugify(heading.text));
        checked += 1;
      }
    }
    // A slug sweep that found no headings would pass on an empty loop.
    expect(checked).toBeGreaterThan(100);
  });

  it("walks meta.json into the same groups and the same page order", () => {
    const mine = buildGroupIndex(docsRoot);
    const theirs = desktopBuildGroupIndex(docsRoot);

    expect(mine.orderedPageIds).toStrictEqual(theirs.orderedPageIds);
    expect([...mine.groupByPage.entries()]).toStrictEqual([
      ...theirs.groupByPage.entries(),
    ]);
  });
});

describe("the corpus web actually serves", () => {
  const corpus = readDocsCorpus(docsRoot, DOCS_SITE_URL);

  it("offers every page the meta.json walk ordered, and no more", () => {
    // Asserted against the WALK, not against `corpus.pages`: every nav row is
    // copied off a page already in that map, so comparing the two would be true
    // by construction and no parser bug could turn it red.
    const rows = corpus.navGroups.flatMap((group) => group.pages);
    expect(rows.map((row) => row.path).sort()).toStrictEqual(
      [...buildGroupIndex(docsRoot).orderedPageIds].sort()
    );
  });

  it("names its groups, so the nav pane is not one unlabelled list", () => {
    expect(corpus.navGroups.length).toBeGreaterThan(1);
    for (const group of corpus.navGroups) {
      expect(group.pages.length).toBeGreaterThan(0);
      // The empty string is what an ungrouped page buckets under, and a corpus
      // that lost its `meta.json` titles would land every page there while still
      // satisfying the two counts above.
      expect(group.group, group.pages[0]?.path).not.toBe("");
    }
  });

  it("indexes a Fumadocs-generated page by its frontmatter and a pointer, like the desktop bundle", () => {
    // The marker branch lives in the desktop generator's ENTRY, not in the lib
    // the parity sweep above imports, so nothing there can see this. Without it
    // every generated page renders its marker COMMENT as its only text and
    // searches as one identical body repeated across all of them.
    const generated = relativePaths.filter((relative) =>
      readFileSync(path.join(docsRoot, relative), "utf8").includes(
        GENERATED_MARKER
      )
    );
    expect(generated.length).toBeGreaterThan(10);

    for (const relative of generated) {
      const pageId = relative.replace(MDX_EXT_RE, "").split(path.sep).join("/");
      const page = corpus.pages.find((candidate) => candidate.path === pageId);

      expect(page, pageId).toBeDefined();
      expect(page?.body, pageId).toBe("");
      expect(page?.headings, pageId).toStrictEqual([]);
      expect(page?.renderBody, pageId).toContain(`${DOCS_SITE_URL}/${pageId}`);
      // The paired negative: the marker itself must not survive into anything
      // the reader sees or the index searches.
      expect(page?.renderBody, pageId).not.toContain(GENERATED_MARKER);
    }
  });

  it("leaves an ordinary prose page with its body and headings", () => {
    // Pairs the sweep above: an `isGenerated` that matched everything would
    // satisfy it and empty the whole corpus.
    const prose = corpus.pages.filter(
      (page) => page.body !== "" && page.headings.length > 0
    );
    expect(prose.length).toBeGreaterThan(50);
  });
});
