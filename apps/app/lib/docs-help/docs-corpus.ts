import { existsSync, readdirSync, readFileSync, statSync } from "node:fs";
import path from "node:path";
import type {
  DocsHelpHeading,
  DocsHelpNavGroup,
  DocsHelpNavPage,
  DocsHelpPage,
} from "@repo/app/help/lib/docs-help-payload";
import { DocsCorpusFailureReason } from "@repo/app/help/lib/web-help-contract";
import { slugifyHeading } from "./docs-slug";

/**
 * ISS-10006 — the WEB host's docs transport.
 *
 * `HelpSurfaceV2` takes a `DocsHelpSource`; producing one is the host's job, and
 * on desktop that is four privileged IPC calls over a docs snapshot packed into
 * the app bundle. Web has no bundle and no IPC: it reads the SAME corpus
 * `apps/web` publishes at closedloop.ai/docs, straight off the repo checkout the
 * deployment ships with, which is why Help needed a mount and a transport rather
 * than a component.
 *
 * THE PARSING RULES ARE A DELIBERATE SECOND COPY of
 * `apps/desktop/scripts/generate-docs-bundle-manifest-lib.mjs`, and
 * `__tests__/docs-corpus-parity.test.ts` holds the two together against the real
 * corpus. Importing that module here would mean `apps/app` runtime code reaching
 * into `apps/desktop`'s build scripts across an app boundary; the repo already
 * answers this exact seam the other way, with a copy and a parity test
 * (`apps/desktop/test/docs-slug-parity.test.ts` does it for the slug alone).
 * A drift in either copy fails that test against a page that really exists.
 */

const MDX_EXT_RE = /\.mdx$/;
const FRONTMATTER_RE = /^---\n([\s\S]*?)\n---\n?/;
const FRONTMATTER_KEY_RE = /^([A-Za-z0-9_-]+):\s*(.*)$/;
const CODE_FENCE_RE = /```[\s\S]*?```/g;
const INLINE_CODE_RE = /`([^`]*)`/g;
const JSX_TAG_RE = /<\/?[A-Za-z][^>]*>/g;
const HTML_COMMENT_RE = /<!--[\s\S]*?-->/g;
const IMAGE_RE = /!\[[^\]]*\]\([^)]*\)/g;
const LINK_RE = /\[([^\]]*)\]\([^)]*\)/g;
const MD_EMPHASIS_RE = /[*_~]{1,3}/g;
const MULTISPACE_RE = /[ \t]+/g;
const MULTI_NEWLINE_RE = /\n{3,}/g;
const CODE_FENCE_SPLIT_RE = /(```[\s\S]*?```)/g;
const FENCE_LEAD_RE = /^```/;
const HEADING_LINE_RE = /^(#{1,6})\s+(.+?)\s*#*$/;
const SEPARATOR_RE = /^---(.+)---$/;

/**
 * Fumadocs stamps this into every page it generates from the OpenAPI spec —
 * everything under `api-reference/`, which is a large minority of the corpus.
 * Their body is one `<APIPage document={…} />` element plus a brace-wrapped JSX
 * comment, not prose, so the desktop generator indexes them by frontmatter alone
 * and points at the live interactive reference
 * (`generate-docs-bundle-manifest.mjs`).
 *
 * WEB HAS TO MAKE THE SAME CALL (tamsinb review): `toRenderMarkdown` strips the
 * JSX element, but a brace-wrapped JSX comment is not an HTML comment and
 * `HTML_COMMENT_RE` leaves it alone. Without this branch every one of those
 * pages RENDERS that marker comment as its only text and SEARCHES as one
 * identical body repeated, so a query for "generated" returns all of them. The
 * parity test cannot see it from the shared lib: the branch lives in the
 * generator's ENTRY, which is why it is asserted directly below.
 */
const GENERATED_MARKER = "This file was generated by Fumadocs";

export function stripQuotes(value: string): string {
  if (value.length >= 2) {
    const first = value[0];
    const last = value.at(-1);
    if ((first === '"' || first === "'") && first === last) {
      return value.slice(1, -1);
    }
  }
  return value;
}

export function parseFrontmatter(raw: string): {
  frontmatter: Record<string, string>;
  body: string;
} {
  const match = raw.match(FRONTMATTER_RE);
  if (match === null) {
    return { body: raw, frontmatter: {} };
  }
  const frontmatter: Record<string, string> = {};
  for (const line of (match[1] ?? "").split("\n")) {
    const kv = line.match(FRONTMATTER_KEY_RE);
    if (kv?.[1] !== undefined && kv[2] !== undefined) {
      frontmatter[kv[1]] = stripQuotes(kv[2].trim());
    }
  }
  return { body: raw.slice(match[0].length), frontmatter };
}

/** Flattened for SEARCH: code, markup and link targets are noise to a matcher. */
export function toPlainText(mdxBody: string): string {
  return mdxBody
    .replace(CODE_FENCE_RE, " ")
    .replace(HTML_COMMENT_RE, " ")
    .replace(IMAGE_RE, " ")
    .replace(JSX_TAG_RE, " ")
    .replace(LINK_RE, "$1")
    .replace(INLINE_CODE_RE, "$1")
    .replace(MD_EMPHASIS_RE, "")
    .replace(MULTISPACE_RE, " ")
    .replace(MULTI_NEWLINE_RE, "\n\n")
    .trim();
}

/** Kept as markdown for the READER, with fenced blocks passed through intact. */
export function toRenderMarkdown(mdxBody: string): string {
  return mdxBody
    .split(CODE_FENCE_SPLIT_RE)
    .map((segment) =>
      FENCE_LEAD_RE.test(segment)
        ? segment
        : segment.replace(HTML_COMMENT_RE, "").replace(JSX_TAG_RE, "")
    )
    .join("")
    .replace(MULTI_NEWLINE_RE, "\n\n")
    .trim();
}

export function extractHeadings(mdxBody: string): DocsHelpHeading[] {
  const withoutFences = mdxBody.replace(CODE_FENCE_RE, "");
  const headings: DocsHelpHeading[] = [];
  for (const line of withoutFences.split("\n")) {
    const match = line.match(HEADING_LINE_RE);
    if (match?.[1] === undefined || match[2] === undefined) {
      continue;
    }
    const level = match[1].length;
    // The frontmatter `title` owns the H1; index only sub-headings (##..######).
    if (level < 2) {
      continue;
    }
    const text = toPlainText(match[2]).trim();
    if (text !== "") {
      headings.push({ level, slug: slugifyHeading(text), text });
    }
  }
  return headings;
}

export function toPageId(relativeMdxPath: string): string {
  return relativeMdxPath.replace(MDX_EXT_RE, "").split(path.sep).join("/");
}

function readMeta(dirAbs: string): Record<string, unknown> | null {
  const metaFile = path.join(dirAbs, "meta.json");
  if (!existsSync(metaFile)) {
    return null;
  }
  try {
    return JSON.parse(readFileSync(metaFile, "utf8")) as Record<
      string,
      unknown
    >;
  } catch {
    return null;
  }
}

/**
 * One `meta.json` entry resolved against the directory it was listed in: whether
 * a page of that name exists beside it, and whether it also names a subtree.
 * Both can be true — Fumadocs allows an index page and a folder under one name.
 */
function resolveNavEntry(
  dirAbs: string,
  entry: string
): { hasPage: boolean; subDir: string | null } {
  const childDir = path.join(dirAbs, entry);
  const isDir = existsSync(childDir) && statSync(childDir).isDirectory();
  return {
    hasPage: existsSync(path.join(dirAbs, `${entry}.mdx`)),
    subDir: isDir ? childDir : null,
  };
}

/**
 * The Fumadocs `meta.json` walk, which is what makes web's nav tree the SAME
 * tree desktop bundles and the docs site renders — group titles, page order and
 * `---Separator---` rows included. A host that sorted alphabetically instead
 * would look right and be a different document.
 */
export function buildGroupIndex(docsRoot: string): {
  groupByPage: Map<string, string>;
  orderedPageIds: string[];
} {
  const groupByPage = new Map<string, string>();
  const orderedPageIds: string[] = [];

  const walkDir = (
    dirAbs: string,
    relPrefix: string,
    inheritedGroup: string | undefined
  ): void => {
    const meta = readMeta(dirAbs);
    const entries = Array.isArray(meta?.pages) ? meta.pages : [];
    let group = typeof meta?.title === "string" ? meta.title : inheritedGroup;
    for (const entry of entries) {
      if (typeof entry !== "string") {
        continue;
      }
      const separator = entry.match(SEPARATOR_RE);
      if (separator?.[1] !== undefined) {
        group = separator[1].trim();
        continue;
      }
      const pageId = `${relPrefix}${entry}`;
      const { hasPage, subDir } = resolveNavEntry(dirAbs, entry);
      if (hasPage && !groupByPage.has(pageId)) {
        groupByPage.set(pageId, group ?? "");
        orderedPageIds.push(pageId);
      }
      if (subDir !== null) {
        walkDir(subDir, `${relPrefix}${entry}/`, group);
      }
    }
  };

  walkDir(docsRoot, "", undefined);
  return { groupByPage, orderedPageIds };
}

/** The whole corpus, parsed once. */
export type DocsCorpus = {
  readonly navGroups: readonly DocsHelpNavGroup[];
  readonly pages: readonly DocsHelpPage[];
};

/**
 * How far above the working directory the bundle root may sit. Same bound, and
 * the same reason, as `MAX_ROOT_DEPTH` in
 * `apps/api/app/preview-schemas/ensure/prisma-runtime-layout.ts`.
 */
const MAX_ROOT_DEPTH = 6;

/** The corpus's path relative to whichever root holds it. */
const DOCS_ROOT_SUFFIX = ["apps", "web", "content", "docs"] as const;

/**
 * The corpus is not in this deployment at all — a PERMANENT fact about the
 * build, not a read that might work next time (marisolashgrove review).
 *
 * Kept apart from every other throw in this module so the routes can say which
 * of the two happened: a missing corpus is a deployment that never shipped the
 * docs, and re-reading it reproduces the same failure forever, while a parse or
 * fs failure is worth another look. Collapsing them gives the reader one
 * "couldn't load just now" sentence that invites a reload over a read that
 * cannot succeed.
 */
export class DocsCorpusMissingError extends Error {
  constructor(searched: readonly string[]) {
    super(`docs corpus not found; looked in ${searched.join(", ")}`);
    this.name = "DocsCorpusMissingError";
  }
}

/**
 * Where the corpus is, found by walking the working directory and its ancestors
 * nearest-first rather than by guessing two layouts.
 *
 * `apps/api` already ships a resolver for exactly this problem
 * (`resolveMigrateRuntimeLayout`), and its docstring says why: Vercel's traced
 * files keep their paths relative to `outputFileTracingRoot` — the monorepo root
 * — while a function's cwd is its own Next project directory, so the bundle root
 * is SOME ancestor of cwd and which one is a platform detail. This shape needs
 * nothing checked against a live deployment to be right, which is the point:
 * the previous two candidates covered cwd being the bundle root or
 * `<root>/apps/app`, and `docs-corpus-tracing.test.ts` can only prove the glob
 * matches in the SOURCE tree. The failure mode it was one platform change away
 * from was a 503 on every Help open with every suite green.
 *
 * A wrong answer raises rather than returning an empty corpus, because "no
 * pages" is the one answer the reader must never be shown for a
 * misconfiguration.
 */
export function resolveDocsRoot(cwd: string = process.cwd()): string {
  const searched: string[] = [];
  let current = cwd;
  for (let depth = 0; depth < MAX_ROOT_DEPTH; depth += 1) {
    const candidate = path.join(current, ...DOCS_ROOT_SUFFIX);
    searched.push(candidate);
    if (existsSync(candidate)) {
      return candidate;
    }
    const parent = path.dirname(current);
    if (parent === current) {
      break;
    }
    current = parent;
  }
  throw new DocsCorpusMissingError(searched);
}

/**
 * Every `.mdx` under `dir`, as paths relative to `docsRoot`. Exported so the
 * parity test can compare THIS walk against the desktop generator's: it is the
 * one rule in the copy that a sweep enumerating with desktop's list would never
 * exercise, and a walk that skipped a directory would leave every other
 * assertion green and the pages simply absent from Help.
 */
export function collectMdxFiles(dir: string, docsRoot: string = dir): string[] {
  const out: string[] = [];
  const entries = existsSync(dir)
    ? readdirSync(dir, { withFileTypes: true })
    : [];
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      out.push(...collectMdxFiles(full, docsRoot));
      continue;
    }
    if (MDX_EXT_RE.test(entry.name)) {
      out.push(path.relative(docsRoot, full));
    }
  }
  return out;
}

/**
 * What a generated reference page offers instead of its body: the frontmatter
 * description, if any, and a link to the interactive reference that IS the page.
 * Kept identical in shape to the desktop generator's `onlinePointer`.
 */
function generatedPagePointer(
  pageId: string,
  docsSiteUrl: string,
  description: string | undefined
): string {
  const link = `[View the full interactive reference online](${docsSiteUrl}/${pageId}).`;
  return description === undefined ? link : `${description}\n\n${link}`;
}

/** One `.mdx` file, read and parsed into the page the surface renders. */
function readDocsPage(
  docsRoot: string,
  relative: string,
  docsSiteUrl: string,
  group: string | undefined
): DocsHelpPage {
  const pageId = toPageId(relative);
  const raw = readFileSync(path.join(docsRoot, relative), "utf8");
  const { frontmatter, body } = parseFrontmatter(raw);
  const isGenerated = raw.includes(GENERATED_MARKER);
  const description = frontmatter.description?.trim();
  return {
    body: isGenerated ? "" : toPlainText(body),
    headings: isGenerated ? [] : extractHeadings(body),
    path: pageId,
    renderBody: isGenerated
      ? generatedPagePointer(pageId, docsSiteUrl, description)
      : toRenderMarkdown(body),
    title: frontmatter.title ?? pageId,
    ...(description === undefined || description === "" ? {} : { description }),
    ...(group === undefined || group === "" ? {} : { group }),
  };
}

/**
 * Nav order is the meta.json order, not the filesystem's. A page the nav tree
 * never names is still READABLE by path — it just has no row, exactly as on the
 * docs site.
 */
function buildNavGroups(
  orderedPageIds: readonly string[],
  byId: ReadonlyMap<string, DocsHelpPage>
): DocsHelpNavGroup[] {
  const navGroups: DocsHelpNavGroup[] = [];
  for (const pageId of orderedPageIds) {
    const page = byId.get(pageId);
    if (page === undefined) {
      continue;
    }
    const group = page.group ?? "";
    const navPage: DocsHelpNavPage = {
      path: page.path,
      title: page.title,
      ...(page.group === undefined ? {} : { group: page.group }),
    };
    const existing = navGroups.find((candidate) => candidate.group === group);
    if (existing === undefined) {
      navGroups.push({ group, pages: [navPage] });
      continue;
    }
    (existing.pages as DocsHelpNavPage[]).push(navPage);
  }
  return navGroups;
}

export function readDocsCorpus(
  docsRoot: string,
  docsSiteUrl: string
): DocsCorpus {
  const { groupByPage, orderedPageIds } = buildGroupIndex(docsRoot);
  const byId = new Map<string, DocsHelpPage>();

  for (const relative of collectMdxFiles(docsRoot)) {
    const pageId = toPageId(relative);
    byId.set(
      pageId,
      readDocsPage(docsRoot, relative, docsSiteUrl, groupByPage.get(pageId))
    );
  }

  return {
    navGroups: buildNavGroups(orderedPageIds, byId),
    pages: [...byId.values()],
  };
}

/**
 * Which of the two failures this was (marisolashgrove review).
 *
 * The cache retries on every request, which is right for a transient read and
 * wrong for a corpus that is not in the bundle: that one re-walks the tree,
 * re-throws, and hands the reader "couldn't load just now" on every single
 * reload, forever. The distinction is available at the source, so it is carried
 * rather than collapsed — the route reports it and the surface says something
 * the reader can act on.
 *
 * Here rather than beside the cache so a route test can stub the corpus read
 * without also stubbing the classification the route exists to report.
 */
export function docsCorpusFailureReason(
  error: unknown
): DocsCorpusFailureReason {
  return error instanceof DocsCorpusMissingError
    ? DocsCorpusFailureReason.NotDeployed
    : DocsCorpusFailureReason.ReadFailed;
}
